import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  white: "FFFFFF",
  muted: "64748B",
  border: "E2E8F0",
};

export const generatePpt = async (data) => {
  try {
    const ppt = new pptxgen();
    ((ppt.layout = "LAYOUT_WIDE"), (ppt.author = "PowerAI"));
    ppt.title = data.title;
    ppt.subject = data.title;
    ppt.company = "PowerAI";
    ppt.theme = {
      headFontFace: "Aptos",
      bodyFontFace: "Aptos",
    };

    addCover(ppt, data);

    data?.slides?.forEach((slide, i) => {

      addContentSlide(ppt, slide.title, slide.points, i + 1, data.slides.length)
    });

    addThankYou(ppt);

    return ppt;
  } catch (error) {
     console.log("GENERATE PPT ERROR:", error);
  throw error;
  }
};

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();
  slide.background = {
    color: COLORS.primary,
  };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.3,
    h: 0.18,
    fill: {
      color: "60A5FA",
    },
    line: {
      color: "60A5FA",
    }
  });

  slide.addText(String(data.title ?? ""), {
    x: 0.7,
    y: 1.7,
    w: 12,
    h: 0.8,
    align:"center",
    color: COLORS.white,
    bold: true,
    fontSize: 34,
  });

  slide.addText(String(data.subtitle ?? ""), {
    x: 1,
    y: 2.7,
    w: 11.5,
    h: 0.4,
    align: "center",
    color: "DBEAFE",
    fontSize: 15,
  });

  slide.addText("Generated By PowerAI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "BFDBFE",
    fontSize: 10,
  });
};

const addContentSlide = (ppt, title, points, page, total) => {
  const slide = ppt.addSlide();
  slide.background = {
    color: COLORS.white,
  };

  slide.addText(String(title ?? ""), {
    x: 0.6,
    y: 0.35,
    w: 10,
    h: 0.4,
    color: COLORS.primary,
    bold: true,
    fontSize: 24,
  });

  slide.addShape(ppt.ShapeType.line, {
    x: 0.6,
    y: 0.85,
    w: 12,
    h: 0,
    line: {
      color: COLORS.border,
      width: 1.2,
    },
  });

  const visiblePoints = points.slice(0, 6);

  visiblePoints.forEach((point, i) => {
    const y = 1.2 + i * 0.75;

    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.7,
      y,
      w: 12,
      h: 0.58,
      line: {
        color: COLORS.border,
      },
      fill: {
        color: i % 2 ? "F8FAFC" : "EFF6FF",
      },
      radius: 0.08,
    });

    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.92,
      y: y + 0.18,
      w: 0.1212,
      h: 0.12,
      line: {
        color: COLORS.primary,
      },
      fill: {
        color: COLORS.primary,
      },
    });

    slide.addText(String(point ?? ""), {
      x: 1.2,
      y: y + 0.08,
      w: 11,
      h: 0.35,
      color: COLORS.text,
      fontSize: 15,
      fit: "shrink",
    });

    slide.addText(`${page}/${total}`, {
      x: 12.1,
      y: 6.9,
      w: 0.8,
      h: 0.2,
      align: "right",
      color: COLORS.muted,
      fontSize: 10,
    });

    slide.addText(`PowerAI`, {
      x: 0.6,
      y: 6.9,
      w: 2,
      h: 0.2,
      color: COLORS.muted,
      fontSize: 10,
    });
  });
};

